#!/usr/bin/env python3
"""Prioritize high-confidence AMP predictions with the ExpFrame workflow."""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
SRC_DIR = REPO_ROOT / "src"
if str(SRC_DIR) not in sys.path:
    sys.path.insert(0, str(SRC_DIR))

from framo_amp.expframe import (  # noqa: E402
    embedding_evidence,
    load_embeddings,
    load_high_confidence_candidates,
    load_reference_fasta,
    prioritize_candidates,
    read_foldseek_hits,
    read_mmseqs_hits,
    run_foldseek,
    run_mmseqs,
    write_expframe_outputs,
)
from framo_amp.data import write_fasta  # noqa: E402


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--predictions-tsv", type=Path, required=True)
    parser.add_argument("--positive-reference-fasta", type=Path, required=True)
    parser.add_argument("--sequence-reference-fasta", type=Path, default=None,
                        help="AMP_P/high-confidence sequence reference; defaults to positive reference FASTA.")
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--min-ensemble-score", type=float, default=2.0 / 3.0)
    parser.add_argument("--sequence-evalue", type=float, default=1e-3)
    parser.add_argument("--structure-tm-score", type=float, default=0.5)
    parser.add_argument("--embedding-quantile", type=float, default=0.95)
    parser.add_argument("--distance-chunk-size", type=int, default=2048)
    parser.add_argument("--threads", type=int, default=16)

    sequence = parser.add_argument_group("sequence-similarity evidence")
    sequence.add_argument("--mmseqs-results", type=Path,
                          help="Existing headerless TSV: query,target,evalue,...")
    sequence.add_argument("--run-mmseqs", action="store_true")
    sequence.add_argument("--mmseqs-bin", default="mmseqs")

    structure = parser.add_argument_group("structure-similarity evidence")
    structure.add_argument("--foldseek-results", type=Path,
                           help="Existing TSV: query,target,evalue,alntmscore[,qtmscore,ttmscore].")
    structure.add_argument("--run-foldseek", action="store_true")
    structure.add_argument("--candidate-structure-dir", type=Path,
                           help="Directory of candidate PDB/mmCIF files generated by ESMFold.")
    structure.add_argument("--reference-structure-dir", type=Path,
                           help="Directory of positive AMP reference PDB/mmCIF files.")
    structure.add_argument("--foldseek-bin", default="foldseek")

    embedding = parser.add_argument_group("ESM2 CLS embedding evidence")
    embedding.add_argument("--candidate-embeddings", type=Path)
    embedding.add_argument("--candidate-metadata", type=Path)
    embedding.add_argument("--reference-embeddings", type=Path)
    embedding.add_argument("--reference-metadata", type=Path)
    embedding.add_argument("--esm2-model-dir", type=Path,
                           help="Automatically extract CLS embeddings with this local ESM2-650M model.")
    embedding.add_argument("--gpus", default="0")
    embedding.add_argument("--embedding-batch-size", type=int, default=32)
    parser.add_argument(
        "--allow-partial",
        action="store_true",
        help="Allow missing sequence, structure, or embedding modules; missing evidence cannot retain candidates.",
    )
    return parser.parse_args()


def _all_or_none(args: argparse.Namespace, names: tuple[str, ...]) -> bool:
    values = [getattr(args, name) is not None for name in names]
    if any(values) and not all(values):
        flags = ", ".join("--" + name.replace("_", "-") for name in names)
        raise ValueError(f"provide all or none of: {flags}")
    return all(values)


def main() -> None:
    args = parse_args()
    if not 0.0 <= args.min_ensemble_score <= 1.0:
        raise ValueError("--min-ensemble-score must be in [0, 1]")
    if args.threads <= 0 or args.distance_chunk_size <= 0:
        raise ValueError("--threads and --distance-chunk-size must be positive")

    output_dir = args.output_dir.resolve()
    work_dir = output_dir / "work"
    work_dir.mkdir(parents=True, exist_ok=True)
    candidates, audit = load_high_confidence_candidates(
        args.predictions_tsv, args.min_ensemble_score
    )
    candidate_fasta = work_dir / "high_confidence_candidates.fasta"
    write_fasta(((item.seq_id, item.sequence) for item in candidates), candidate_fasta)
    references = load_reference_fasta(args.positive_reference_fasta)
    cleaned_reference_fasta = work_dir / "positive_reference.cleaned.fasta"
    write_fasta(references, cleaned_reference_fasta)

    mmseqs_results = args.mmseqs_results
    if args.run_mmseqs:
        if mmseqs_results is not None:
            raise ValueError("choose either --run-mmseqs or --mmseqs-results")
        mmseqs_results = work_dir / "mmseqs_hits.tsv"
        run_mmseqs(
            args.mmseqs_bin,
            candidate_fasta,
            args.sequence_reference_fasta or cleaned_reference_fasta,
            mmseqs_results,
            work_dir / "mmseqs_tmp",
            args.threads,
            args.sequence_evalue,
        )
    sequence_hits = read_mmseqs_hits(mmseqs_results, args.sequence_evalue) if mmseqs_results else {}

    foldseek_results = args.foldseek_results
    if args.run_foldseek:
        if foldseek_results is not None:
            raise ValueError("choose either --run-foldseek or --foldseek-results")
        if args.candidate_structure_dir is None or args.reference_structure_dir is None:
            raise ValueError("--run-foldseek requires both structure directories")
        foldseek_results = work_dir / "foldseek_hits.tsv"
        run_foldseek(
            args.foldseek_bin,
            args.candidate_structure_dir,
            args.reference_structure_dir,
            foldseek_results,
            work_dir / "foldseek_tmp",
            args.threads,
        )
    structure_hits = read_foldseek_hits(foldseek_results, args.structure_tm_score) if foldseek_results else {}

    embedding_names = (
        "candidate_embeddings",
        "candidate_metadata",
        "reference_embeddings",
        "reference_metadata",
    )
    if args.esm2_model_dir is not None:
        if any(getattr(args, name) is not None for name in embedding_names):
            raise ValueError("choose either --esm2-model-dir or the four precomputed embedding files")
        embedding_dir = work_dir / "esm2_cls"
        embedding_dir.mkdir(parents=True, exist_ok=True)
        subprocess.run(
            [
                sys.executable,
                str(REPO_ROOT / "scripts" / "extract_esm2_embeddings.py"),
                str(candidate_fasta),
                str(cleaned_reference_fasta),
                "--model-dir",
                str(args.esm2_model_dir),
                "--model-name",
                "esm2_t33_650M_UR50D",
                "--output-dir",
                str(embedding_dir),
                "--gpus",
                args.gpus,
                "--batch-size",
                str(args.embedding_batch_size),
                "--pooling",
                "cls",
                "--model-dtype",
                "float16",
                "--output-dtype",
                "float32",
                "--canonical-only",
                "--overwrite",
            ],
            check=True,
        )
        candidate_prefix = embedding_dir / "high_confidence_candidates.esm2_t33_650M_UR50D.cls"
        reference_prefix = embedding_dir / "positive_reference.cleaned.esm2_t33_650M_UR50D.cls"
        args.candidate_embeddings = Path(str(candidate_prefix) + ".npy")
        args.candidate_metadata = Path(str(candidate_prefix) + ".metadata.tsv")
        args.reference_embeddings = Path(str(reference_prefix) + ".npy")
        args.reference_metadata = Path(str(reference_prefix) + ".metadata.tsv")
    have_embeddings = _all_or_none(args, embedding_names)
    embeddings = {}
    if have_embeddings:
        candidate_ids, candidate_matrix = load_embeddings(args.candidate_embeddings, args.candidate_metadata)
        reference_ids, reference_matrix = load_embeddings(args.reference_embeddings, args.reference_metadata)
        expected_candidate_ids = {item.seq_id for item in candidates}
        if set(candidate_ids) != expected_candidate_ids:
            missing = sorted(expected_candidate_ids.difference(candidate_ids))[:10]
            extra = sorted(set(candidate_ids).difference(expected_candidate_ids))[:10]
            raise ValueError(f"candidate embedding IDs differ; missing={missing}, extra={extra}")
        if set(reference_ids) != {item[0] for item in references}:
            raise ValueError("reference embedding IDs differ from positive reference FASTA")
        embeddings = embedding_evidence(
            candidate_ids,
            candidate_matrix,
            reference_ids,
            reference_matrix,
            quantile=args.embedding_quantile,
            chunk_size=args.distance_chunk_size,
        )

    missing_modules = [
        name
        for name, present in (
            ("sequence", mmseqs_results is not None),
            ("structure", foldseek_results is not None),
            ("embedding", have_embeddings),
        )
        if not present
    ]
    if missing_modules and not args.allow_partial:
        raise ValueError(
            "missing ExpFrame evidence modules: " + ", ".join(missing_modules)
            + "; provide their inputs or use --allow-partial"
        )

    rows = prioritize_candidates(candidates, sequence_hits, structure_hits, embeddings)
    write_expframe_outputs(output_dir, rows, audit)
    retained = sum(int(row["retained"]) for row in rows)
    print(
        f"ExpFrame candidates={len(rows)} retained={retained} "
        f"sequence={sum(row['expframe_class'] == 'sequence_similarity' for row in rows)} "
        f"structure={sum(row['expframe_class'] == 'structure_similarity' for row in rows)} "
        f"divergent={sum(row['expframe_class'] == 'divergent_generation' for row in rows)}"
    )
    print(f"wrote {output_dir / 'expframe_results.tsv'}")
    print(f"wrote {output_dir / 'retained_amp.fasta'}")


if __name__ == "__main__":
    main()
